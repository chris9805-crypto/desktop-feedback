type EtfInit = Omit<EtfSecurity, "kind" | "fund" | "breakdown"> & {
  fund: Partial<EtfSecurity["fund"]> & Pick<EtfSecurity["fund"], "expenseRatio" | "aumUsd" | "indexName">;
  breakdown: Partial<EtfSecurity["breakdown"]>;
};

function etf(init: EtfInit): EtfSecurity {
  return {
    kind: "etf",
    ...init,
    fund: {
      inceptionYear: 2010,
      domicile: "US",
      replication: "physicalFull",
      distribution: "distributing",
      holdingsCount: 500,
      spread: 0.0002,
      trackingDifference: -0.0002,
      currencyHedged: false,
      ...init.fund,
    },
    breakdown: {
      assetClass: {},
      region: {},
      sector: {},
      size: {},
      style: {},
      factor: {},
      credit: {},
      currency: {},
      ...init.breakdown,
    },
  };
}

